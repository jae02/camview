def update_file(filepath):
    if not os.path.exists(filepath):
        print(f"Skipping {filepath} (Not found)")
        return 0
        
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f)
        
    updated = 0
    for item in data:
        slug = item.get('slug', '').lower()
        if slug in custom_descriptions:
            item['description'] = custom_descriptions[slug]
            updated += 1
            print(f"Updated description for {slug} in {os.path.basename(filepath)}")
            
    if updated > 0:
        with open(filepath, 'w', encoding='utf-8') as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            
    return updated

def main():
    base_dir = os.path.join(os.path.dirname(__file__), '..', 'data')
    seeds_path = os.path.join(base_dir, 'seeds', 'all_cameras_seed.json')
    reviews_path = os.path.join(base_dir, 'cameradecision_reviews', '_all_reviews.json')
    
    total = 0
    total += update_file(seeds_path)
    total += update_file(reviews_path)
    
    print(f"Done! Updated a total of {total} items across JSON files.")

if __name__ == "__main__":
    main()
